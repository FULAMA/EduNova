from tools.edunova.agents.orchestration.adapter import ProviderAdapter
from tools.edunova.agents.orchestration.executor import ProviderExecutor
from tools.edunova.agents.provider import AgentProvider
from tools.edunova.agents.result import AgentResult
from tools.edunova.agents.role import AgentRole


class FakeAdapter(ProviderAdapter):
    def generate(
        self,
        provider: AgentProvider,
        task: str,
    ) -> AgentResult:
        return AgentResult(
            agent=provider.name,
            role=AgentRole.BUILDER,
            success=True,
            message=f"Generated by {provider.name}: {task}",
        )


class AdapterExecutor(ProviderExecutor):
    def __init__(self, adapter: ProviderAdapter) -> None:
        self._adapter = adapter

    def execute_provider(
        self,
        provider: AgentProvider,
        task: str,
    ) -> AgentResult:
        return self._adapter.generate(provider, task)


def test_adapter_generates_result() -> None:
    adapter = FakeAdapter()

    result = adapter.generate(
        AgentProvider("gemini"),
        "analyze EduNova",
    )

    assert result.success
    assert result.agent == "gemini"


def test_adapter_receives_task() -> None:
    adapter = FakeAdapter()

    result = adapter.generate(
        AgentProvider("openrouter"),
        "review architecture",
    )

    assert result.message == (
        "Generated by openrouter: review architecture"
    )


def test_executor_delegates_to_adapter() -> None:
    adapter = FakeAdapter()
    executor = AdapterExecutor(adapter)

    result = executor.execute(
        AgentProvider("local"),
        "inspect code",
    )

    assert result.success
    assert result.agent == "local"
    assert result.message == "Generated by local: inspect code"


def test_adapter_executor_keeps_provider_abstraction() -> None:
    adapter = FakeAdapter()
    executor = AdapterExecutor(adapter)

    provider = AgentProvider("test-provider")

    result = executor.execute(provider, "test task")

    assert result.agent == provider.name


def test_adapter_cannot_be_instantiated_without_generate() -> None:
    try:

        class InvalidAdapter(ProviderAdapter):
            pass

        InvalidAdapter()
    except TypeError:
        pass
    else:
        raise AssertionError(
            "ProviderAdapter must be abstract."
        )
